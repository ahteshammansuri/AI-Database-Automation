CREATE TABLE users (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE, company VARCHAR(100) NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE contacts (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INT NOT NULL, phone VARCHAR(20) NULL, city VARCHAR(60) NULL, CONSTRAINT fk_contacts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE leads (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id INT NOT NULL, title VARCHAR(120) NOT NULL, stage VARCHAR(20) NOT NULL, value DECIMAL(12,2) NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, CONSTRAINT fk_leads_owner FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE RESTRICT);
