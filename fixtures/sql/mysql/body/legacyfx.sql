CREATE TABLE tbl_ord_hdr (
  ord_id INT NOT NULL PRIMARY KEY,
  acct_id INT NOT NULL,
  ord_amt DECIMAL(12,2) NOT NULL,
  ord_dt DATETIME NOT NULL,
