CREATE TABLE tbl_acct_main (
  acct_id INT NOT NULL PRIMARY KEY,
  usr_nm VARCHAR(100) NOT NULL,
  eml_addr VARCHAR(190) NOT NULL,
  pwd_hsh VARCHAR(255) NOT NULL,
