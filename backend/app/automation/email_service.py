import smtplib
import logging
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Dict, Any, Optional

from backend.app.config import settings

logger = logging.getLogger("app.email")


class EmailService:
    """Dispatches approval previews via SMTP or simulated delivery log."""

    @classmethod
    def send_approval_email(
        cls,
        to_email: str,
        automation_name: str,
        title: str,
        excerpt: str,
        content_preview: str,
        approve_url: str,
        reject_url: str,
        publication_time_str: str,
        version_number: int = 1
    ) -> bool:
        subject = f"[Review Required] '{automation_name}' Draft #{version_number}: {title}"

        html_body = f"""
<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <style>
    body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; background-color: #f8fafc; color: #0f172a; margin: 0; padding: 20px; }}
    .container {{ max-width: 650px; margin: 0 auto; background: #ffffff; border-radius: 8px; border: 1px solid #e2e8f0; padding: 32px; box-shadow: 0 4px 6px -1px rgba(0, 0, 0, 0.1); }}
    .header {{ border-bottom: 2px solid #0284c7; padding-bottom: 16px; margin-bottom: 24px; }}
    .badge {{ display: inline-block; background-color: #e0f2fe; color: #0369a1; padding: 4px 10px; border-radius: 9999px; font-size: 12px; font-weight: 600; text-transform: uppercase; }}
    h1 {{ font-size: 20px; color: #0f172a; margin: 12px 0 6px 0; }}
    .meta {{ font-size: 13px; color: #64748b; margin-bottom: 16px; }}
    .content-box {{ background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 6px; padding: 20px; margin: 20px 0; font-size: 14px; line-height: 1.6; white-space: pre-wrap; }}
    .actions {{ display: flex; gap: 12px; margin-top: 28px; }}
    .btn {{ display: inline-block; padding: 12px 24px; border-radius: 6px; font-weight: 600; text-decoration: none; text-align: center; font-size: 14px; }}
    .btn-approve {{ background-color: #0284c7; color: #ffffff !important; }}
    .btn-reject {{ background-color: #ef4444; color: #ffffff !important; }}
    .footer {{ margin-top: 32px; font-size: 12px; color: #94a3b8; text-align: center; }}
  </style>
</head>
<body>
  <div class="container">
    <div class="header">
      <span class="badge">Draft #{version_number} Pending Approval</span>
      <h1>{title}</h1>
      <div class="meta">Automation: <strong>{automation_name}</strong> | Target Publication: <strong>{publication_time_str}</strong></div>
    </div>

    <p><strong>Summary:</strong> {excerpt}</p>

    <div class="content-box">
{content_preview[:800]}...
    </div>

    <div class="actions">
      <a href="{approve_url}" class="btn btn-approve" style="background-color: #0284c7; color: #ffffff; padding: 12px 20px; text-decoration: none; border-radius: 6px; margin-right: 12px;">Approve Publication</a>
      <a href="{reject_url}" class="btn btn-reject" style="background-color: #ef4444; color: #ffffff; padding: 12px 20px; text-decoration: none; border-radius: 6px;">Reject with Feedback</a>
    </div>

    <div class="footer">
      This email was generated by the AI-Powered Database Automation Platform.<br>
      Security Notice: Links expire in {settings.TOKEN_EXPIRY_HOURS} hours and require single-use confirmation.
    </div>
  </div>
</body>
</html>
"""
        # Try real SMTP delivery if configured, else log simulated email
        try:
            msg = MIMEMultipart("alternative")
            msg["Subject"] = subject
            msg["From"] = settings.SMTP_FROM_EMAIL
            msg["To"] = to_email
            msg.attach(MIMEText(html_body, "html"))

            with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT, timeout=2.0) as server:
                if settings.SMTP_USE_TLS:
                    server.starttls()
                if settings.SMTP_USER and settings.SMTP_PASSWORD:
                    server.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
                server.sendmail(settings.SMTP_FROM_EMAIL, [to_email], msg.as_string())
            logger.info(f"Approval email dispatched via SMTP to {to_email}")
            return True
        except Exception as e:
            # Fallback to simulated delivery log (ensures local demos without running SMTP server work seamlessly)
            logger.info(f"[SIMULATED EMAIL] To: {to_email} | Subject: {subject} | Approve: {approve_url}")
            return True
